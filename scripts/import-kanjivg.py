#!/usr/bin/env python3
"""Rebuild the 46-character teaching dataset from a pinned KanjiVG revision.

Uses only the Python standard library. Downloaded SVGs are transient input;
only their unmodified, ordered path `d` values are included in the app.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REVISION = "610091ce618cf757ed1357a8954cd65283e015d6"
BASE = f"https://raw.githubusercontent.com/KanjiVG/kanjivg/{REVISION}/"
GROUPS = [
    ("a", "あ行", [("a", "あ"), ("i", "い"), ("u", "う"), ("e", "え"), ("o", "お")]),
    ("k", "か行", [("ka", "か"), ("ki", "き"), ("ku", "く"), ("ke", "け"), ("ko", "こ")]),
    ("s", "さ行", [("sa", "さ"), ("shi", "し"), ("su", "す"), ("se", "せ"), ("so", "そ")]),
    ("t", "た行", [("ta", "た"), ("chi", "ち"), ("tsu", "つ"), ("te", "て"), ("to", "と")]),
    ("n", "な行", [("na", "な"), ("ni", "に"), ("nu", "ぬ"), ("ne", "ね"), ("no", "の")]),
    ("h", "は行", [("ha", "は"), ("hi", "ひ"), ("fu", "ふ"), ("he", "へ"), ("ho", "ほ")]),
    ("m", "ま行", [("ma", "ま"), ("mi", "み"), ("mu", "む"), ("me", "め"), ("mo", "も")]),
    ("y", "や行", [("ya", "や"), ("yu", "ゆ"), ("yo", "よ")]),
    ("r", "ら行", [("ra", "ら"), ("ri", "り"), ("ru", "る"), ("re", "れ"), ("ro", "ろ")]),
    ("w", "わ・を・ん", [("wa", "わ"), ("wo", "を"), ("n", "ん")]),
]
ALIASES = {"shi": ["si"], "chi": ["ti"], "tsu": ["tu"], "fu": ["hu"], "wo": ["o"]}
MANIFEST = ROOT / "scripts" / "kanjivg-manifest.json"
ATTRIBUTION = """KanjiVG stroke data — Creative Commons Attribution-ShareAlike 3.0 Unported

Copyright (C) 2009/2010/2011 Ulrich Apel.
Project: https://kanjivg.tagaini.net/
Source: https://github.com/KanjiVG/kanjivg
License: https://creativecommons.org/licenses/by-sa/3.0/
Pinned revision: 610091ce618cf757ed1357a8954cd65283e015d6

This app selects 46 modern basic hiragana. The SVG path d values and their
order are retained verbatim. XML wrappers, drawing styles, stroke-number
labels and non-kana metadata are omitted. The extracted path dataset in
src/data/kana.ts remains licensed under CC BY-SA 3.0. Other project files
have their own licenses. No endorsement by KanjiVG is implied.

The upstream COPYING file follows, unmodified:

"""


def get_file(path: str, cache: Path | None) -> tuple[str, bytes]:
    cache_path = cache / path if cache else None
    if cache_path is not None and cache_path.is_file():
        return path, cache_path.read_bytes()
    request = urllib.request.Request(BASE + path, headers={"User-Agent": "practice-hiragana-data-importer"})
    with urllib.request.urlopen(request, timeout=45) as response:
        data = response.read()
    if cache_path is not None:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        cache_path.write_bytes(data)
    return path, data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, help="Optional directory for original downloads; do not commit it.")
    parser.add_argument("--update-hashes", action="store_true", help="Intentionally regenerate the pinned-source SHA-256 manifest.")
    args = parser.parse_args()
    paths = [f"kanji/{ord(char):05x}.svg" for _, _, kana in GROUPS for _, char in kana] + ["COPYING"]
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        downloads = dict(pool.map(lambda path: get_file(path, args.cache), paths))
    hashes = {path: hashlib.sha256(downloads[path]).hexdigest() for path in sorted(paths)}
    if args.update_hashes:
        MANIFEST.write_text(json.dumps({"revision": REVISION, "baseUrl": BASE, "sha256": hashes}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    else:
        recorded = json.loads(MANIFEST.read_text(encoding="utf-8"))
        if recorded["revision"] != REVISION or recorded["sha256"] != hashes:
            raise SystemExit("Source hash mismatch; no generated files were changed.")
    kana_data = []
    group_data = []
    for group_id, label, members in GROUPS:
        group_data.append({"id": group_id, "label": label, "kanaIds": [romaji for romaji, _ in members]})
        for romaji, char in members:
            source = downloads[f"kanji/{ord(char):05x}.svg"]
            svg = ET.fromstring(source)
            if svg.attrib.get("viewBox") != "0 0 109 109":
                raise ValueError(f"Unexpected coordinate system for {char}")
            strokes = [path.attrib["d"] for path in svg.iter("{http://www.w3.org/2000/svg}path")]
            if not strokes:
                raise ValueError(f"No strokes for {char}")
            kana_data.append({"id": romaji, "char": char, "romaji": romaji, "group": group_id, "aliases": ALIASES.get(romaji, []), "strokes": strokes})
    header = """/**
 * Generated by scripts/import-kanjivg.py. Do not hand-edit stroke paths.
 * SPDX-License-Identifier: CC-BY-SA-3.0
 * KanjiVG © 2009/2010/2011 Ulrich Apel. https://kanjivg.tagaini.net/
 * Source revision: 610091ce618cf757ed1357a8954cd65283e015d6
 * Selected/repackaged from SVG; path geometry and stroke order are unmodified.
 * This extracted dataset remains under CC BY-SA 3.0:
 * https://creativecommons.org/licenses/by-sa/3.0/
 * Full attribution/license: public/licenses/kanjivg.txt; see DATA_SOURCES.md.
 */

export interface Kana {
  id: string;
  char: string;
  romaji: string;
  group: string;
  aliases: string[];
  /** Ordered KanjiVG SVG path data in viewBox 0 0 109 109. */
  strokes: string[];
}

export interface KanaGroup {
  id: string;
  label: string;
  kanaIds: string[];
}

"""
    output = header + "export const GROUPS: KanaGroup[] = " + json.dumps(group_data, ensure_ascii=False, indent=2) + ";\n\n"
    output += "export const KANA: Kana[] = " + json.dumps(kana_data, ensure_ascii=False, indent=2) + ";\n"
    target = ROOT / "src/data/kana.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output, encoding="utf-8")
    license_path = ROOT / "public/licenses/kanjivg.txt"
    license_path.parent.mkdir(parents=True, exist_ok=True)
    license_path.write_text(ATTRIBUTION + downloads["COPYING"].decode("utf-8"), encoding="utf-8")
    print(f"Generated {len(kana_data)} kana, {sum(len(kana['strokes']) for kana in kana_data)} strokes ({target.stat().st_size:,} bytes); source hashes verified.")


if __name__ == "__main__":
    main()
